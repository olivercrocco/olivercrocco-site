// Build the Poetry of Work registry that the website reads.
//
// Single source of truth: the caption.txt files in the Poetry of Work posts
// folder, plus the card images in public/poetry-of-work/. This script parses
// those, computes each week's go-live date from the posting cadence, and writes
// src/data/poetry-of-work.json. The website imports that JSON and picks the
// current week by date, so it advances on its own each Monday (once rebuilt)
// and can never drift from the captions that actually go out on social.
//
// Run:  npm run poetry:build
// The POSTS_DIR default points at Ozzie's Poetry of Work folder; override with
// the POETRY_POSTS_DIR env var if the archive moves. Netlify never runs this
// (it builds from the committed JSON); it is a local authoring step.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, "..");

const POSTS_DIR =
  process.env.POETRY_POSTS_DIR ||
  "/Users/oz/Desktop/LSU/Research/Public and Creative Work/Poetry of Work/posts";
const IMAGES_DIR = join(REPO, "public", "poetry-of-work");
const OUT = join(REPO, "src", "data", "poetry-of-work.json");

// Cadence anchor. Week 2 went out Monday 2026-07-06 at 14:00 UTC (9:00 AM US
// Central); every later week is one week apart at the same hour. Week 1 was an
// off-cycle launch on 2026-07-03. This mirrors Buffer's live schedule, which is
// the ground truth for what is actually published. (The posting-calendar.csv
// post_date column is one week late and is not used here.)
const ANCHOR_WEEK = 2;
const ANCHOR_UTC = Date.UTC(2026, 6, 6, 14, 0, 0); // 2026-07-06T14:00:00Z
const WEEK_MS = 7 * 24 * 60 * 60 * 1000;
const WEEK1_OVERRIDE = "2026-07-03T14:00:00.000Z";

function goLive(week) {
  if (week === 1) return WEEK1_OVERRIDE;
  return new Date(ANCHOR_UTC + (week - ANCHOR_WEEK) * WEEK_MS).toISOString();
}

function cardsFor(week) {
  const prefix = `w${String(week).padStart(2, "0")}-`;
  return readdirSync(IMAGES_DIR)
    .filter((f) => f.startsWith(prefix) && f.endsWith(".jpg"))
    .sort(
      (a, b) =>
        Number(a.match(/-(\d+)\.jpg$/)[1]) - Number(b.match(/-(\d+)\.jpg$/)[1])
    )
    .map((f) => `/poetry-of-work/${f}`);
}

function parseCaption(text) {
  const lines = text
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  const firstPara = lines[0];
  const creditLine = lines.find((l) => /Public domain\. Source:/.test(l));
  const photoLine = lines.find((l) => l.startsWith("Photograph:"));
  if (!creditLine) throw new Error("no credit line found");
  if (!photoLine) throw new Error("no Photograph line found");

  const poet = creditLine.split(', "')[0].trim();
  const titleMatch = creditLine.match(/"([^"]+)"/);
  if (!titleMatch) throw new Error("no title in credit line");
  const title = titleMatch[1];

  const datesMatch = firstPara.match(/\(([^)]*\bto\b[^)]*)\)/);
  if (!datesMatch) throw new Error("no poet dates in first paragraph");
  const dates = datesMatch[1].trim();

  // poemCredit = the caption's credit line with the poet's life dates inserted
  // after the name, matching the site's established "Poet (dates), ..." format.
  const poemCredit = `${poet} (${dates})${creditLine.slice(poet.length)}`;

  return { poet, dates, title, poemCredit, photoCredit: photoLine };
}

function main() {
  const dirs = readdirSync(POSTS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^W\d{2} - /.test(d.name))
    .map((d) => ({ week: Number(d.name.slice(1, 3)), name: d.name }))
    .sort((a, b) => a.week - b.week);

  const weeks = [];
  const problems = [];
  for (const { week, name } of dirs) {
    try {
      const caption = readFileSync(
        join(POSTS_DIR, name, "caption.txt"),
        "utf8"
      ).trim();
      const parsed = parseCaption(caption);
      const cards = cardsFor(week);
      if (cards.length === 0)
        throw new Error(`no card images (public/poetry-of-work/w${String(week).padStart(2, "0")}-*.jpg)`);
      weeks.push({ week, goLive: goLive(week), ...parsed, cards, caption });
    } catch (err) {
      problems.push(`  W${String(week).padStart(2, "0")} (${name}): ${err.message}`);
    }
  }

  if (problems.length) {
    console.error("Skipped weeks with problems:\n" + problems.join("\n"));
  }
  if (weeks.length === 0) {
    console.error("No weeks parsed. Is POETRY_POSTS_DIR correct? " + POSTS_DIR);
    process.exit(1);
  }

  const registry = {
    _comment:
      "GENERATED by scripts/build-poetry-registry.mjs from the Poetry of Work caption files and card images. Do not edit by hand; run `npm run poetry:build` to regenerate. The website picks the current week by goLive date at build time.",
    generatedFromWeeks: weeks.length,
    weeks,
  };
  writeFileSync(OUT, JSON.stringify(registry, null, 2) + "\n");
  console.log(
    `Wrote ${weeks.length} weeks (W${String(weeks[0].week).padStart(2, "0")}–W${String(
      weeks[weeks.length - 1].week
    ).padStart(2, "0")}) to ${OUT.replace(REPO + "/", "")}`
  );
}

main();
